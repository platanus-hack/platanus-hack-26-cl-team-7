"""CLI: python -m eval run | check-baseline | lock | verify-lock | base-rate | synth."""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Callable, Sequence
from pathlib import Path

from eval.base_rate import RATIO, BaseRateRun, load_patterns, run_base_rate
from eval.baseline import check_baseline, current_values, load_baseline
from eval.lock import verify_lock, write_lock
from eval.report import evaluate, format_report
from eval.synthetic import synthetic_humans, write_pair

Handler = Callable[[argparse.Namespace], int]


def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    handler: Handler = args.handler
    try:
        return handler(args)
    except (ValueError, OSError) as error:
        print(f"eval: {error}", file=sys.stderr)
        return 2


def _run(args: argparse.Namespace) -> int:
    report = evaluate(args.data, args.split, args.routes, args.rules)
    print(format_report(report))
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(f"\nreport written to {args.report}")
    return 0


def _check_baseline(args: argparse.Namespace) -> int:
    report = evaluate(args.data, args.split, args.routes, args.rules)
    problems = check_baseline(current_values(report), load_baseline(args.baseline))
    for problem in problems:
        print(f"baseline: {problem}", file=sys.stderr)
    if not problems:
        print(f"baseline: precision and recall within tolerance of {args.baseline}")
    return 1 if problems else 0


def _lock(args: argparse.Namespace) -> int:
    write_lock(args.test_dir, args.lock)
    print(f"locked {args.test_dir} into {args.lock}")
    return 0


def _verify_lock(args: argparse.Namespace) -> int:
    problems = verify_lock(args.test_dir, args.lock)
    for problem in problems:
        print(f"lock: {problem}", file=sys.stderr)
    if not problems:
        print(f"lock: {args.test_dir} matches {args.lock}")
    return 1 if problems else 0


def _base_rate(args: argparse.Namespace) -> int:
    run = BaseRateRun(
        args.routes, args.rules, args.data / args.split, args.humans, args.seed, args.ratio
    )
    result = run_base_rate(run)
    print(json.dumps(result, indent=2))
    return 0


def _synth(args: argparse.Namespace) -> int:
    sessions = synthetic_humans(load_patterns(args.routes), args.count, args.seed, args.start_ts)
    notes = f"generated by eval.synthetic, seed {args.seed}; not recorded from real people"
    path = write_pair(args.out, args.name, sessions, notes)
    print(f"wrote {len(sessions)} synthetic human sessions to {path}")
    return 0


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="python -m eval", description=__doc__)
    commands = parser.add_subparsers(required=True, metavar="COMMAND")
    run = _command(commands, "run", _run, "score one split and write the JSON report")
    _replay_options(run)
    run.add_argument("--report", type=Path, default=Path("eval/report.json"))
    check = _command(commands, "check-baseline", _check_baseline, "fail on a precision/recall drop")
    _replay_options(check)
    check.add_argument("--baseline", type=Path, default=Path("eval/baseline.json"))
    for name, handler in (("lock", _lock), ("verify-lock", _verify_lock)):
        locker = _command(commands, name, handler, f"{name} the test split hash file")
        locker.add_argument("--test-dir", type=Path, default=Path("eval/data/test"))
        locker.add_argument("--lock", type=Path, default=Path("eval/testset.lock"))
    rate = _command(commands, "base-rate", _base_rate, "false alarms at 1 probe per RATIO humans")
    _replay_options(rate)
    rate.add_argument("--humans", type=int, default=20_000)
    rate.add_argument("--seed", type=int, default=1)
    rate.add_argument("--ratio", type=int, default=RATIO)
    synth = _command(commands, "synth", _synth, "write a synthetic human jsonl + labels pair")
    synth.add_argument("--routes", type=Path, default=Path("config/routes.yaml"))
    synth.add_argument("--out", type=Path, required=True)
    synth.add_argument("--name", default="synthetic_humans")
    synth.add_argument("--count", type=int, default=200)
    synth.add_argument("--seed", type=int, default=1)
    synth.add_argument("--start-ts", type=float, default=1_700_000_000.0)
    return parser


def _command(
    commands: argparse._SubParsersAction[argparse.ArgumentParser],
    name: str,
    handler: Handler,
    help_text: str,
) -> argparse.ArgumentParser:
    command = commands.add_parser(name, help=help_text)
    command.set_defaults(handler=handler)
    return command


def _replay_options(command: argparse.ArgumentParser) -> None:
    command.add_argument("--data", type=Path, default=Path("eval/data"))
    command.add_argument("--split", choices=("tune", "test"), default="test")
    command.add_argument("--routes", type=Path, default=Path("config/routes.yaml"))
    command.add_argument("--rules", type=Path, default=Path("config/rules.yaml"))


if __name__ == "__main__":
    sys.exit(main())
