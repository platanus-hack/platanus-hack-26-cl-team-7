"""Replay CSIC 2010 anomalous requests through the local Caddy proxy as probing sessions.

    python -m eval.convert.csic_replay RAW_DIR [--proxy 127.0.0.1:8080] [--log run/access.log]
        [--out eval/data] [--sessions 60] [--seed 2010] [--delay 0.05]

Each request carries a tag header (token plus session index), so the recorder finds its own lines
in a log that other recorders write to at the same time. Every real request comes from 127.0.0.1;
the tag is then removed and each session gets its own 10.210.x.y address.
"""

from __future__ import annotations

import argparse
import http.client
import json
import sys
import time
import uuid
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from engine.models import Label, session_key
from eval.convert.csic import (
    CsicRequest,
    assign_splits,
    plan_sessions,
    read_dump,
    rewrite_line,
    session_ip,
    write_pair,
)

TAG_HEADER = "X-Csic-Recorder"
NAME = "csic-anomalous"


@dataclass(frozen=True)
class Recording:
    proxy: str
    log: Path
    out: Path
    delay: float = 0.05
    flush_timeout: float = 10.0
    token: str = ""


def send(proxy: str, req: CsicRequest, tag: str) -> int | None:
    """Send one request; the status code, or None when the proxy drops the connection."""
    headers = {"User-Agent": req.user_agent, TAG_HEADER: tag, "Connection": "close"}
    if req.body:
        headers["Content-Type"] = req.content_type or "application/x-www-form-urlencoded"
    conn = http.client.HTTPConnection(proxy, timeout=5)
    try:
        conn.request(req.method, req.target, body=req.body or None, headers=headers)
        response = conn.getresponse()
        response.read()
        return response.status
    except (OSError, http.client.HTTPException, ValueError):
        return None
    finally:
        conn.close()


def collect(log: Path, offset: int, token: str) -> dict[str, list[str]]:
    """Lines appended after `offset` whose tag header starts with `token`, keyed by tag."""
    found: dict[str, list[str]] = {}
    with log.open("rb") as handle:
        handle.seek(offset)
        for raw in handle:
            line = raw.decode("utf-8", errors="replace").rstrip("\n")
            tag = _tag(line)
            if tag is not None and tag.startswith(token + "-"):
                found.setdefault(tag, []).append(line)
    return found


def _tag(line: str) -> str | None:
    try:
        entry = json.loads(line)
    except ValueError:
        return None
    headers = entry.get("request", {}).get("headers", {}) if isinstance(entry, dict) else {}
    values = headers.get(TAG_HEADER) if isinstance(headers, dict) else None
    return values[0] if isinstance(values, list) and values else None


def record(sessions: Sequence[Sequence[CsicRequest]], rec: Recording, seed: int) -> dict[str, int]:
    """Replay, wait for Caddy to log every answered request, then write the tune/test pairs."""
    token = rec.token or f"csic-{uuid.uuid4().hex[:12]}"
    offset = rec.log.stat().st_size
    answered = 0
    for index, session in enumerate(sessions):
        for req in session:
            answered += send(rec.proxy, req, f"{token}-{index}") is not None
            time.sleep(rec.delay)
    found = _wait_for(rec, offset, token, answered)
    splits = assign_splits(len(sessions), seed)
    lines: dict[str, list[str]] = {"tune": [], "test": []}
    labels: dict[str, dict[str, Label]] = {"tune": {}, "test": {}}
    for index, split in enumerate(splits):
        ip, own = session_ip(index), found.get(f"{token}-{index}", [])
        lines[split].extend(rewrite_line(line, ip, TAG_HEADER) for line in own)
        if own:
            labels[split][session_key(ip, sessions[index][0].user_agent)] = "probing"
    for split in ("tune", "test"):
        write_pair(rec.out / split, NAME, lines[split], labels[split], _notes(rec, seed))
    return {
        "sent": sum(len(s) for s in sessions),
        "answered": answered,
        "logged": sum(len(v) for v in lines.values()),
        "tune_sessions": len(labels["tune"]),
        "test_sessions": len(labels["test"]),
    }


def _wait_for(rec: Recording, offset: int, token: str, expected: int) -> dict[str, list[str]]:
    deadline = time.monotonic() + rec.flush_timeout
    found = collect(rec.log, offset, token)
    while sum(len(v) for v in found.values()) < expected and time.monotonic() < deadline:
        time.sleep(0.2)
        found = collect(rec.log, offset, token)
    return found


def _notes(rec: Recording, seed: int) -> str:
    return (
        "CSIC 2010 HTTP dataset anomalousTrafficTest.txt (public; requests generated by the "
        "CSIC authors). Runs of 10-30 consecutive attack requests were replayed through the "
        f"local Caddy proxy ({rec.proxy}, demo site behind it, {rec.delay}s apart, seed "
        f"{seed}); the logged lines are real Caddy output except client_ip/remote_ip, "
        "rewritten to one 10.210.x.y address per session (all replays came from 127.0.0.1), "
        "and the recorder tag header, removed. Request bodies of POST/PUT were sent but Caddy "
        "logs only the URI. Original CSIC Konqueror User-Agent kept. Every session is labeled "
        "probing."
    )


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m eval.convert.csic_replay")
    parser.add_argument("raw_dir", type=Path, help="directory holding anomalousTrafficTest.txt")
    parser.add_argument("--proxy", default="127.0.0.1:8080")
    parser.add_argument("--log", type=Path, default=Path("run/access.log"))
    parser.add_argument("--out", type=Path, default=Path("eval/data"))
    parser.add_argument("--sessions", type=int, default=60)
    parser.add_argument("--seed", type=int, default=2010)
    parser.add_argument("--delay", type=float, default=0.05)
    args = parser.parse_args(argv)
    try:
        dump = read_dump(args.raw_dir / "anomalousTrafficTest.txt")
        sessions = plan_sessions(dump, args.sessions, args.seed)
        rec = Recording(args.proxy, args.log, args.out, args.delay)
        print(json.dumps(record(sessions, rec, args.seed), indent=2))
    except (OSError, ValueError) as error:
        print(f"csic_replay: {error}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
